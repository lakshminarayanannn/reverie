"""``reverie install claude-code``: write the hook script and print a settings snippet.

It never edits the user's Claude Code settings. The snippet uses exec-form hooks
(``command`` + ``args``, no shell), so paths with spaces work on every platform.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from reverie.core.config import data_dir
from reverie.core.fsutil import atomic_write_text

HOOK_SCRIPT = '''"""reverie hook entry point for Claude Code (generated by `reverie install claude-code`)."""
import sys

from reverie.online.hooks import main

sys.exit(main(sys.argv[1:]))
'''


def settings_snippet(python: str, script: str, memory: str, config: str | None = None,
                     targeted_recall: bool = False) -> dict[str, Any]:
    def hook(event: str, timeout: int | None = None) -> dict[str, Any]:
        args = [script, event, "--memory", memory] + (["--config", config] if config else [])
        h: dict[str, Any] = {"type": "command", "command": python, "args": args}
        if timeout:
            h["timeout"] = timeout
        return h

    post_matcher = "Read|Bash|Edit|Write" if targeted_recall else "Read|Bash"
    return {"hooks": {
        "SessionStart": [{"hooks": [hook("session-start", 10)]}],
        "PreToolUse": [{"matcher": "Bash", "hooks": [hook("pre-tool-use", 10)]}],
        "PostToolUse": [{"matcher": post_matcher, "hooks": [hook("post-tool-use", 10)]}],
        "Stop": [{"hooks": [hook("capture", 30)]}],
        "SessionEnd": [{"hooks": [hook("capture", 30)]}],
    }}


def install_claude_code(memory: Path, config: Path | None = None, out_dir: Path | None = None,
                        targeted_recall: bool = False) -> dict[str, Any]:
    target = Path(out_dir) if out_dir else data_dir() / "claude-code"
    script = target / "reverie_hook.py"
    atomic_write_text(script, HOOK_SCRIPT)
    snippet = settings_snippet(sys.executable, str(script.resolve()), str(Path(memory).resolve()),
                               str(Path(config).resolve()) if config else None, targeted_recall)
    snippet_path = target / "settings-snippet.json"
    atomic_write_text(snippet_path, json.dumps(snippet, indent=2) + "\n")
    return {"script": str(script), "snippet_path": str(snippet_path), "snippet": snippet}


DEVIN_PLUGIN_NAME = "reverie-memory"


def devin_hooks(python: str, script: str, memory: str, config: str | None = None) -> dict[str, Any]:
    """Devin CLI hooks schema (``hooks.json`` in a plugin, or ``.devin/hooks.v1.json``)."""
    import shlex

    def hook(event: str, timeout: int) -> dict[str, Any]:
        parts = [python, script, event, "--agent", "devin", "--memory", memory]
        if config:
            parts += ["--config", config]
        return {"type": "command", "command": shlex.join(parts), "timeout": timeout}

    return {
        "SessionStart": [{"hooks": [hook("session-start", 10)]}],
        "UserPromptSubmit": [{"hooks": [hook("user-prompt-submit", 10)]}],
        "PreToolUse": [{"matcher": "exec", "hooks": [hook("pre-tool-use", 10)]}],
        "PostToolUse": [{"hooks": [hook("post-tool-use", 10)]}],
        "Stop": [{"hooks": [hook("capture", 30)]}],
        "SessionEnd": [{"hooks": [hook("capture", 30)]}],
    }


def install_devin(memory: Path, config: Path | None = None, out_dir: Path | None = None) -> dict[str, Any]:
    """Write a local Devin plugin (hooks only). Install it with ``devin plugins install --local <dir>``."""
    target = Path(out_dir) if out_dir else data_dir() / "devin"
    script = target / "reverie_hook.py"
    atomic_write_text(script, HOOK_SCRIPT)
    plugin = target / DEVIN_PLUGIN_NAME
    hooks = devin_hooks(sys.executable, str(script.resolve()), str(Path(memory).resolve()),
                        str(Path(config).resolve()) if config else None)
    manifest = {"name": DEVIN_PLUGIN_NAME, "version": "0.1.0",
                "description": "Inject reviewed memory at session start, capture sessions for dreaming, run guards.",
                "license": "Apache-2.0"}
    atomic_write_text(plugin / ".devin-plugin" / "plugin.json", json.dumps(manifest, indent=2) + "\n")
    atomic_write_text(plugin / "hooks.json", json.dumps(hooks, indent=2) + "\n")
    return {"script": str(script), "plugin_dir": str(plugin), "hooks": hooks,
            "install_command": f"devin plugins install --local {plugin}"}
